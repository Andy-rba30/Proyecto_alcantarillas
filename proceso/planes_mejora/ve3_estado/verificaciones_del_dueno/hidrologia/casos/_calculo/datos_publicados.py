def espol_series():
    """Anexo 2 (tesis.pdf PDF 94-96, imp. 89-91): 4 estaciones INAMHI."""
    pags = _paginas("espol.txt")
    texto = "\n".join(pags[93:96])
    texto = texto[texto.index("P max 24 H"):texto.index("Total (n)")]
    faltas = {1974: 1, 1987: 1, 1999: 2}     # columna con «-» en la linea del año
    series = {"La Argelia": {}, "Gonzanama": {}, "Malacatos": {}, "Catamayo": {}}
    nombres = list(series)
    anio = None
    for linea in texto.split("\n"):
        m = re.match(r"\s*(19\d\d|20\d\d)\b", linea)
        if m:
            anio = int(m.group(1)); continue
        tok = linea.split()
        if anio is None or not tok or not re.match(r"^[\d.]+$|^-$", tok[0]):
            continue
        if not all(re.match(r"^\d+\.\d\d$|^-$", t) for t in tok):
            continue
        if anio in faltas:
            tok.insert(faltas[anio], "-")
        assert len(tok) == 4, (anio, tok)
        for nombre, t in zip(nombres, tok):
            if t != "-":
                series[nombre][anio] = float(t)
        anio = None
    return series
