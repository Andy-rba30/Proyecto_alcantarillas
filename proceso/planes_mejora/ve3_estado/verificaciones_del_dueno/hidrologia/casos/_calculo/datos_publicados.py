def tumbes_serie():
    """Tabla 24 (tesis.pdf p. 61): N, AÑO, P24."""
    pag = _paginas("tumbes.txt")[60]
    serie = {}
    for m in re.finditer(r"\b(\d{1,2}) (\d{4}) (\d+\.\d\d)\b", pag):
        serie[int(m.group(2))] = float(m.group(3))
    return serie

def tumbes_mensual():
    """Tabla 23 (p. 60): año -> 12 valores mensuales."""
    pag = _paginas("tumbes.txt")[59]
    out = {}
    for linea in pag.split("\n"):
        m = re.match(r"\s*(\d{4})\s+((?:\d+\.\d+\s+){12})(\d+\.\d+)\s+(\w+)", linea)
        if m:
            out[int(m.group(1))] = ([float(x) for x in m.group(2).split()],
                                    float(m.group(3)), m.group(4))
    return out

